for filename in os.listdir(PERSONAS_DIR):
    if not filename.endswith(".json"):
        continue
    filepath = os.path.join(PERSONAS_DIR, filename)
    persona_id = filename.replace(".json", "")

    if persona_id not in PERSONA_EXTRAS:
        print(f"  ⚠ 跳过 {persona_id}: 没有定义新字段")
        continue

    with open(filepath, "r", encoding="utf-8") as f:
        data = json.load(f)

    extras = PERSONA_EXTRAS[persona_id]
    data["appearance"] = extras["appearance"]
    data["speech_patterns"] = extras["speech_patterns"]
    data["first_mes"] = extras["first_mes"]
    data["mes_example"] = extras["mes_example"]

    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"  ✅ {persona_id}: 已添加 appearance, speech_patterns, first_mes, mes_example (4段对话)")

